import { expect, test } from '@playwright/test';
import { completeEvent, newGame } from '../../src/arcade/engine';

test('native migration retains v1, isolates quick exploration and restores the campaign after reload', async ({ page }) => {
  test.setTimeout(90_000);
  const old = { ...completeEvent(newGame(), 'freelance'), timed: false };
  old.chapters.freelance.energy = 55;
  const original = JSON.stringify(old);
  const scripts: string[] = [];
  page.on('request', request => { if (request.resourceType() === 'script') scripts.push(request.url()); });
  await page.addInitScript(raw => { if (!localStorage.getItem('antonios:career:v1')) localStorage.setItem('antonios:career:v1', raw); }, original);
  await page.goto('/en/arcade/?nativeArcade=1');
  await page.locator('.arcade-launcher button').click();
  await expect(page.locator('.godot-world')).toHaveAttribute('data-engine', 'ready', { timeout: 60_000 });
  await expect(page.getByRole('status').filter({ hasText: 'Previous game imported' })).toBeVisible();
  const read = () => page.evaluate(() => JSON.parse(localStorage.getItem('antonios:career:v2')!));
  const before = await read();
  expect(before.campaign.chapters.freelance.energy).toBe(55);
  expect(await page.evaluate(() => localStorage.getItem('antonios:career:v1'))).toBe(original);
  expect(scripts.some(url => url.includes('ExistingCareerGame'))).toBe(false);
  await page.getByRole('button', { name: 'Game and missions', exact: true }).click();
  await page.getByRole('button', { name: /^Practice: / }).first().click();
  await expect(page.locator('.godot-world')).toHaveAttribute('data-map', 'freelance');
  await expect.poll(async () => Object.keys((await read()).quick).length).toBeGreaterThan(0);
  const during = await read();
  expect(during.campaign).toEqual(before.campaign);
  expect(during.campaign_exploration.world).toBe('town');
  await page.reload();
  await page.locator('.arcade-launcher button').click();
  await expect(page.locator('.godot-world')).toHaveAttribute('data-engine', 'ready', { timeout: 60_000 });
  await page.getByRole('button', { name: 'Game and missions', exact: true }).click();
  await page.getByRole('button', { name: 'Return to my campaign', exact: true }).click();
  await expect(page.locator('.godot-world')).toHaveAttribute('data-map', 'town');
  const after = await read();
  expect(after.campaign).toEqual(before.campaign);
  expect(after.quick).toEqual({});
  expect(after.positions).toEqual(before.positions);
  expect(after.quests).toEqual(before.quests);
  expect(after.completed).toEqual(before.completed);
  expect(after.campaign_exploration).toEqual({});
});

test('unreadable native saves remain protected until an explicit new game confirmation', async ({ page }) => {
  test.setTimeout(90_000);
  await page.addInitScript(() => localStorage.setItem('antonios:career:v2', '{broken save'));
  await page.goto('/arcade/?nativeArcade=1');
  await page.locator('.arcade-launcher button').click();
  await expect(page.locator('.godot-world')).toHaveAttribute('data-engine', 'ready', { timeout: 60_000 });
  await expect(page.getByRole('alert').filter({ hasText: 'guardado está protegido' })).toBeVisible();
  await page.getByRole('button', { name: 'Entrar en Freelance', exact: true }).click();
  await expect(page.locator('.godot-world')).toHaveAttribute('data-map', 'freelance');
  expect(await page.evaluate(() => localStorage.getItem('antonios:career:v2'))).toBe('{broken save');
  await page.getByRole('button', { name: 'Partida y misiones', exact: true }).click();
  await page.getByRole('button', { name: 'Nueva campaña…', exact: true }).click();
  expect(await page.evaluate(() => localStorage.getItem('antonios:career:v2'))).toBe('{broken save');
  await page.getByRole('button', { name: 'Sí, empezar de nuevo', exact: true }).click();
  await expect(page.locator('.godot-world')).toHaveAttribute('data-map', 'town');
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('antonios:career:v2')!).version)).toBe(2);
  await expect(page.getByRole('alert').filter({ hasText: 'guardado está protegido' })).toHaveCount(0);
});
