import { townSpawn, buildings } from '../../src/arcade/town';
import { makePixelMap, mapCamera, mapProject } from '../../src/arcade/pixel-map';
import { companyArt } from '../../src/arcade/company-art';
import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { clickCanvasPoint, dumpGodotDebugBestEffort, enableGodotE2EDebug, waitForGodotInteraction } from './career-fixture';

test.use({ reducedMotion: 'reduce', launchOptions: { args: ['--enable-unsafe-swiftshader'] } });
test.beforeEach(async ({ page }) => enableGodotE2EDebug(page));
test.afterEach(async ({ page }, testInfo) => { if (testInfo.status !== testInfo.expectedStatus) await dumpGodotDebugBestEffort(page, testInfo); });
for (const engine of ['desktop', 'mobile']) test(`${engine}: explore town, locked doors, enter and leave, preserve world across languages`, async ({ page }) => {
  test.setTimeout(60000);
  if (engine === 'mobile') await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/arcade/'); await expect(page.locator('[data-ready="true"]')).toBeVisible();
  await page.locator('.arcade-launcher button').click();
  await expect(page.locator('[data-chapter="xul"]')).toBeDisabled();
  await page.getByRole('button', { name: 'Nueva partida', exact: false }).click();
  const world = page.locator('.godot-world');
  await expect(world).toHaveAttribute('data-engine', 'ready', { timeout: 60000 });
  await expect(world).toHaveAttribute('data-map', 'town');
  await expect(world).toHaveAttribute('data-godot-map', 'town');
  await expect(world).toHaveAttribute('data-player', `${townSpawn.x},${townSpawn.y}`);
  // A future building is reachable, but approaching it cannot start a locked chapter.
  await clickCanvasPoint(page, { x: companyArt.xul.door[0], y: companyArt.xul.door[1] - 7 }, 'town-locked-xul');
  await waitForGodotInteraction(page, 'xul', 'Aún no te contratan');
  await expect(page.locator('.career-status')).toContainText('Puerta cerrada');
  await expect(page.getByRole('dialog')).toContainText('Aún no te contratan');
  await expect(page.getByRole('dialog')).toContainText('Solo es cambiar un botón');
  await page.getByRole('dialog').getByRole('button', { name: 'Cerrar', exact: true }).click();
  await expect(world).toHaveAttribute('data-map', 'town');
  await clickCanvasPoint(page, { x: companyArt.freelance.door[0], y: companyArt.freelance.door[1] - 7 }, 'town-freelance');
  await expect(world).toHaveAttribute('data-map', 'freelance', { timeout: 30_000 });
  await expect(world).toHaveAttribute('data-godot-map', 'freelance');
  await page.locator('.career-game-heading').getByRole('button', { name: 'Volver a la ciudad' }).click();
  await expect(world).toHaveAttribute('data-map', 'town');
  await expect(world).toHaveAttribute('data-godot-map', 'town');
  const returned = buildings.find(b => b.id === 'freelance')!.door;
  await expect(world).toHaveAttribute('data-player', `${returned.x},${returned.y}`);
  await page.getByRole('button', { name: 'Caminar al este', exact: true }).click();
  await expect(world).toHaveAttribute('data-player', `${returned.x + 1},${returned.y}`);
  await page.locator('.career-world a[data-language]').click();
  await expect(page).toHaveURL('/en/arcade/?career=continue');
  await expect(world).toHaveAttribute('data-map', 'town');
  await expect(world).toHaveAttribute('data-player', `${returned.x + 1},${returned.y}`);
  await expect(page.locator('.career-game-heading h1')).toHaveText('Career Town');
  await expect(page.locator('[data-company="xul"]')).toBeDisabled();
  await expect(world).toHaveAttribute('data-engine', 'ready', { timeout: 60000 });
  await page.locator('.career-world').evaluate(el => { el.scrollTop = 0; });
  await page.screenshot({ path: `test-results/town-${engine}.png`, fullPage: true });
  await page.getByRole('button', { name: 'Follow the character', exact: true }).click();
  await expect(world).toHaveAttribute('data-zoom', '2');
  const map = makePixelMap('town', [], 'en');
  const camera = mapCamera(map, returned.x + 1, returned.y, 2);
  const target = mapProject(map, returned.x + 2.5, returned.y + .5);
  await clickCanvasPoint(page, { x: (target.x - camera.x) * 2, y: (target.y - camera.y) * 2 }, 'town-zoom');
  await expect(world).toHaveAttribute('data-player', `${returned.x + 2},${returned.y}`);
  await page.locator('.career-game-heading').scrollIntoViewIfNeeded();
  await page.screenshot({ path: `test-results/town-zoom-${engine}.png`, fullPage: true });
  expect(await page.locator('.career-world').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
  expect((await new AxeBuilder({ page }).include('.career-world').withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([]);
});
